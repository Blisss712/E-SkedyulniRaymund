import { isSupabaseConfigured, supabase } from "../../lib/supabase"
import type {
  JoinRequest,
  JoinRequestStatus,
  Organization,
  OrganizationDraft,
  OrganizationStatus,
} from "../admin/types"
import type { Ministry } from "../../shared/home"

/**
 * The single source of truth for organizations.
 *
 * Every surface that talks about an organization - the admin workspace
 * (Organizations, Dashboard metrics, the Events organization picker), the
 * member dashboard's "My Ministries" sheet, and the join-request flow - reads
 * and writes through this module so they can never disagree.
 *
 * When the optional FastAPI backend is configured the `/admin` endpoints own
 * the data (see `features/admin/api.ts`). Otherwise the browser talks to the
 * Supabase tables directly:
 *
 *   organizations                  - the organizations/ministries themselves
 *   organization_member_accounts   - approved memberships
 *   organization_join_requests     - pending/approved/rejected requests
 *
 * Row-level security on the server keeps members to their own rows while
 * administrators can read and manage everything.
 */

const ORGANIZATION_COLUMNS =
  "id, name, description, contact_email, phone, timezone, address, category, status, join_code, created_at"

const JOIN_REQUEST_COLUMNS =
  "id, organization_id, member_user_id, member_name, submitted_join_code, status, requested_at, reviewed_at"

type OrganizationRow = {
  id: string
  name: string
  description: string | null
  contact_email: string | null
  phone: string | null
  timezone: string | null
  address: string | null
  category: string | null
  status: string | null
  join_code: string | null
  created_at: string | null
}

type EmbeddedOrganization = {
  id?: string | null
  name: string | null
  category?: string | null
}

type JoinRequestRow = {
  id: string
  organization_id: string
  member_user_id: string | null
  member_name: string
  submitted_join_code: string
  status: string
  requested_at: string
  reviewed_at: string | null
  organizations?: EmbeddedOrganization | EmbeddedOrganization[] | null
}

/** PostgREST returns a to-one embed as an object, but an array on some clients. */
function embeddedOrganization(
  value: JoinRequestRow["organizations"],
): EmbeddedOrganization | null {
  if (!value) return null
  return Array.isArray(value) ? value[0] ?? null : value
}

function organizationFromRow(row: OrganizationRow): Organization {
  return {
    id: row.id,
    name: row.name,
    joinCode: row.join_code ?? undefined,
    description: row.description ?? "",
    contactEmail: row.contact_email ?? "",
    phone: row.phone ?? "",
    timezone: row.timezone ?? "Asia/Manila",
    address: row.address ?? "",
    category: row.category ?? "Parish",
    status: (row.status === "inactive" ? "inactive" : "active") as OrganizationStatus,
    createdAt: (row.created_at ?? "").slice(0, 10),
  }
}

/** Only the columns an administrator edits; `join_code` is generated by the server. */
function organizationValues(draft: OrganizationDraft) {
  return {
    name: draft.name.trim(),
    description: draft.description,
    contact_email: draft.contactEmail.trim(),
    phone: draft.phone,
    timezone: draft.timezone.trim() || "Asia/Manila",
    address: draft.address,
    category: draft.category.trim() || "Parish",
    status: draft.status,
  }
}

function joinRequestFromRow(row: JoinRequestRow): JoinRequest {
  const organization = embeddedOrganization(row.organizations)
  return {
    id: row.id,
    organizationId: row.organization_id,
    memberName: row.member_name,
    groupCode: row.submitted_join_code,
    // The organization's current name wins so a renamed organization is shown
    // consistently everywhere, including on requests submitted before the rename.
    groupName: organization?.name || row.submitted_join_code,
    status: row.status as JoinRequestStatus,
    requestedAt: row.requested_at,
    reviewedAt: row.reviewed_at,
  }
}

function describe(error: { message?: string } | null, fallback: string) {
  return new Error(error?.message?.trim() || fallback)
}

// ─── Organizations ───────────────────────────────────────────────────────────

/**
 * Reads the organizations this session is allowed to see: every organization
 * for an administrator, the active ones for a member.
 */
export async function fetchOrganizations(): Promise<Organization[]> {
  if (!isSupabaseConfigured) return []
  const { data, error } = await supabase
    .from("organizations")
    .select(ORGANIZATION_COLUMNS)
    .order("name", { ascending: true })
  if (error) throw describe(error, "Unable to load organizations.")
  return ((data ?? []) as OrganizationRow[]).map(organizationFromRow)
}

export async function createOrganizationRow(
  id: string,
  draft: OrganizationDraft,
): Promise<Organization> {
  const { data, error } = await supabase
    .from("organizations")
    .insert({ id, ...organizationValues(draft) })
    .select(ORGANIZATION_COLUMNS)
    .single()
  if (error) throw describe(error, "Unable to create the organization.")
  return organizationFromRow(data as OrganizationRow)
}

export async function updateOrganizationRow(
  id: string,
  draft: OrganizationDraft,
): Promise<Organization> {
  const { data, error } = await supabase
    .from("organizations")
    .update(organizationValues(draft))
    .eq("id", id)
    .select(ORGANIZATION_COLUMNS)
    .single()
  if (error) throw describe(error, "Unable to save the organization.")
  return organizationFromRow(data as OrganizationRow)
}

export async function setOrganizationStatusRow(
  id: string,
  status: OrganizationStatus,
): Promise<Organization> {
  const { data, error } = await supabase
    .from("organizations")
    .update({ status })
    .eq("id", id)
    .select(ORGANIZATION_COLUMNS)
    .single()
  if (error) throw describe(error, "Unable to change the organization's status.")
  return organizationFromRow(data as OrganizationRow)
}

export async function deleteOrganizationRow(id: string): Promise<void> {
  const { error } = await supabase.from("organizations").delete().eq("id", id)
  if (error) throw describe(error, "Unable to delete the organization.")
}

// ─── Join codes ──────────────────────────────────────────────────────────────

export type GroupLookup = { id: string; name: string; category: string }

/**
 * Finds the active organization that owns a join code. Returns `null` when no
 * organization matches so callers can show "we couldn't find that code".
 */
export async function findOrganizationByJoinCode(code: string): Promise<GroupLookup | null> {
  if (!isSupabaseConfigured) return null
  // join_code is matched case-insensitively, so escape LIKE wildcards first.
  const pattern = code.replace(/[\\%_*]/g, character => `\\${character}`)
  const { data, error } = await supabase
    .from("organizations")
    .select("id, name, category")
    .ilike("join_code", pattern)
    .eq("status", "active")
    .limit(1)
    .maybeSingle()
  if (error || !data) return null
  return {
    id: data.id as string,
    name: data.name as string,
    category: (data.category as string | null) ?? "",
  }
}

// ─── Join requests ───────────────────────────────────────────────────────────

/**
 * Join requests visible to this session. An administrator sees every request;
 * a coordinator passes their ministry ids and sees only those, which is also
 * what the database RLS policy enforces.
 */
export async function fetchJoinRequests(organizationIds?: string[]): Promise<JoinRequest[]> {
  // Only a coordinator passes this list; an empty list means no ministry yet.
  if (organizationIds && organizationIds.length === 0) return []

  let query = supabase
    .from("organization_join_requests")
    .select(`${JOIN_REQUEST_COLUMNS}, organizations(name)`)
    .order("requested_at", { ascending: false })

  if (organizationIds) {
    query = query.in("organization_id", organizationIds)
  }

  const { data, error } = await query
  if (error) throw describe(error, "Unable to load join requests.")
  return ((data ?? []) as unknown as JoinRequestRow[]).map(joinRequestFromRow)
}

export async function fetchJoinRequest(id: string): Promise<JoinRequest> {
  const { data, error } = await supabase
    .from("organization_join_requests")
    .select(`${JOIN_REQUEST_COLUMNS}, organizations(name)`)
    .eq("id", id)
    .maybeSingle()
  if (error) throw describe(error, "Unable to load the join request.")
  if (!data) throw new Error("That join request no longer exists.")
  return joinRequestFromRow(data as unknown as JoinRequestRow)
}

export async function createJoinRequestRow(input: {
  memberName: string
  organizationId: string
  groupCode: string
  userId: string
}): Promise<JoinRequest> {
  const { data, error } = await supabase
    .from("organization_join_requests")
    .insert({
      organization_id: input.organizationId,
      member_user_id: input.userId,
      member_name: input.memberName,
      submitted_join_code: input.groupCode,
      status: "pending",
    })
    .select(`${JOIN_REQUEST_COLUMNS}, organizations(name)`)
    .single()
  if (error) throw describe(error, "Unable to submit the join request.")
  return joinRequestFromRow(data as unknown as JoinRequestRow)
}

/** True when PostgREST cannot find the RPC at all, i.e. an older project. */
function isMissingRpc(error: { code?: string; message?: string }): boolean {
  return (
    error.code === "PGRST202" ||
    /could not find the function|function .* does not exist|schema cache/i.test(error.message ?? "")
  )
}

function missingCoordinatorSetup(): Error {
  return new Error(
    "Coordinator join-request approvals are not set up in Supabase yet. Run supabase/coordinator_join_approvals.sql in the Supabase SQL editor, then reload.",
  )
}

/**
 * Records a reviewer's decision.
 *
 * `review_join_request()` (see supabase/coordinator_join_approvals.sql)
 * authorizes an administrator or the coordinator of the request's own ministry
 * and, on approval, creates the membership row in the same transaction. A
 * coordinator's browser has no direct UPDATE policy on the table, so the RPC is
 * the only way they can decide. Administrators keep the older fallbacks for a
 * project that has not run the coordinator migration yet.
 */
export async function reviewJoinRequest(
  id: string,
  status: "approved" | "rejected",
  reviewerId: string,
  options: { coordinator?: boolean } = {},
): Promise<JoinRequest> {
  const reviewed = await supabase.rpc("review_join_request", {
    req_id: id,
    decision: status,
    reviewer_id: reviewerId,
    note: "",
  })

  if (!reviewed.error) return fetchJoinRequest(id)

  // The function exists and refused the decision (another ministry, inactive
  // member, already reviewed). Never bypass that rule with a direct write.
  if (!isMissingRpc(reviewed.error)) {
    throw new Error(reviewed.error.message || "Unable to update the join request.")
  }

  // Older projects do not have the coordinator decision function. A coordinator
  // must not fall back to a direct table write.
  if (options.coordinator) throw missingCoordinatorSetup()

  // Compatibility: projects that installed the administrator-only RPC still
  // work for approvals.
  if (status === "approved") {
    const approved = await supabase.rpc("approve_join_request", {
      req_id: id,
      reviewer_id: reviewerId,
      note: "",
    })
    if (!approved.error) return fetchJoinRequest(id)
    if (!isMissingRpc(approved.error)) {
      throw new Error(approved.error.message || "Unable to approve the join request.")
    }
  }

  const { data, error } = await supabase
    .from("organization_join_requests")
    .update({ status, reviewed_at: new Date().toISOString(), reviewed_by: reviewerId })
    .eq("id", id)
    .select(`${JOIN_REQUEST_COLUMNS}, organizations(name)`)
    .single()
  if (error) throw describe(error, "Unable to update the join request.")

  const row = data as unknown as JoinRequestRow

  if (status === "approved" && row.member_user_id) {
    const membership = await supabase
      .from("organization_member_accounts")
      .upsert(
        { organization_id: row.organization_id, user_id: row.member_user_id },
        { onConflict: "organization_id,user_id", ignoreDuplicates: true },
      )
    if (membership.error) {
      throw new Error(
        `The request was approved, but the membership could not be added: ${membership.error.message}`,
      )
    }
  }

  return joinRequestFromRow(row)
}

// ─── The signed-in member's ministries ───────────────────────────────────────

type MembershipRow = {
  organization_id: string
  organizations?: EmbeddedOrganization | EmbeddedOrganization[] | null
}

type PendingRequestRow = {
  id: string
  organization_id: string
  submitted_join_code: string
  organizations?: EmbeddedOrganization | EmbeddedOrganization[] | null
}

/**
 * Builds the member's "My Ministries" list from the same tables the
 * administrator manages: approved memberships first, then requests still
 * waiting for review.
 */
export async function fetchMyMinistries(userId: string): Promise<Ministry[]> {
  const [memberships, pending] = await Promise.all([
    supabase
      .from("organization_member_accounts")
      .select("organization_id, organizations(name, category)")
      .eq("user_id", userId),
    supabase
      .from("organization_join_requests")
      .select("id, organization_id, submitted_join_code, organizations(name, category)")
      .eq("member_user_id", userId)
      .eq("status", "pending")
      .order("requested_at", { ascending: false }),
  ])

  const failure = memberships.error ?? pending.error
  if (failure) throw describe(failure, "Unable to load your ministries.")

  const joinedIds = new Set<string>()
  const joined: Ministry[] = []
  const awaiting: Ministry[] = []

  for (const row of (memberships.data ?? []) as unknown as MembershipRow[]) {
    const organization = embeddedOrganization(row.organizations)
    joinedIds.add(row.organization_id)
    joined.push({
      id: row.organization_id,
      name: organization?.name || "Organization",
      parish: organization?.category || "Ministry",
    })
  }

  for (const row of (pending.data ?? []) as unknown as PendingRequestRow[]) {
    // A membership already covers this organization; do not list it twice.
    if (joinedIds.has(row.organization_id)) continue
    const organization = embeddedOrganization(row.organizations)
    awaiting.push({
      id: `pending-${row.id}`,
      name: organization?.name || row.submitted_join_code,
      parish: "Waiting for approval",
      waiting: true,
    })
  }

  // Approved ministries first (they can be selected), then pending requests.
  const byName = (a: Ministry, b: Ministry) => a.name.localeCompare(b.name)
  return [...joined.sort(byName), ...awaiting.sort(byName)]
}
